        // ===== Setup tabel + pewarnaan baris =====
    private void siapkanTabel() {
        tableModel = new DefaultTableModel(
                new String[]{"No", "Nama Bahan", "Tanggal Kedaluwarsa", "Status"}, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
        jTable1.setModel(tableModel);
        jTable1.setRowHeight(24);
        jTable1.getColumnModel().getColumn(0).setMaxWidth(40);
        jTable1.getColumnModel().getColumn(3).setPreferredWidth(220);

        jTable1.setDefaultRenderer(Object.class, new DefaultTableCellRenderer() {
            @Override
            public Component getTableCellRendererComponent(JTable tbl, Object value,
                    boolean isSelected, boolean hasFocus, int row, int column) {
                Component c = super.getTableCellRendererComponent(
                        tbl, value, isSelected, hasFocus, row, column);
                String status = String.valueOf(tableModel.getValueAt(row, 3));

                if (!isSelected) {
                    if (status.startsWith("SUDAH") || status.startsWith("HARI INI")) {
                        c.setBackground(MERAH_BG);
                        c.setForeground(new Color(150, 0, 0));
                    } else if (status.startsWith("SEGERA")) {
                        c.setBackground(KUNING_BG);
                        c.setForeground(new Color(120, 70, 0));
                    } else {
                        c.setBackground(Color.WHITE);
                        c.setForeground(Color.BLACK);
                    }
                }
                return c;
            }
        });
    }

