    // ===== Tampilkan laporan JasperReports (Simple_Blue.jrxml) =====
    private void reportActionPerformed(java.awt.event.ActionEvent evt) {
        try (java.io.InputStream in = getClass().getResourceAsStream("/reports/Simple_Blue.jrxml")) {
            if (in == null) {
                throw new java.io.FileNotFoundException("reports/Simple_Blue.jrxml tidak ditemukan di classpath");
            }
            // 1. Compile file .jrxml
            net.sf.jasperreports.engine.JasperReport jr =
                    net.sf.jasperreports.engine.JasperCompileManager.compileReport(in);

            // 2. Koneksi database dari DataSource milik Spring
            javax.sql.DataSource ds = SpringUtil.getContext().getBean("dataSource", javax.sql.DataSource.class);
            try (java.sql.Connection conn = ds.getConnection()) {
                // 3. Isi laporan (tanpa parameter)
                net.sf.jasperreports.engine.JasperPrint jp =
                        net.sf.jasperreports.engine.JasperFillManager.fillReport(
                                jr, new java.util.HashMap<String, Object>(), conn);

                // 4. Tampilkan; false = menutup viewer tidak menutup aplikasi
                net.sf.jasperreports.view.JasperViewer.viewReport(jp, false);
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Gagal mencetak laporan: " + e.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
        }
    }

