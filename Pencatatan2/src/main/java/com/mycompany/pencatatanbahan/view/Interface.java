    // ===== Status berdasarkan sisa hari =====
    private String hitungStatus(LocalDate tanggal, LocalDate hariIni) {
        long sisa = ChronoUnit.DAYS.between(hariIni, tanggal);
        if (sisa < 0) {
            return "SUDAH KEDALUWARSA (" + Math.abs(sisa) + " hari lalu)";
        } else if (sisa == 0) {
            return "HARI INI KEDALUWARSA!";
        } else if (sisa <= BATAS_PERINGATAN) {
            return "SEGERA KEDALUWARSA (H-" + sisa + ")";
        }
        return "Aman";
    }

        private void perbaruiBanner(List<String> kedaluwarsa, List<String> segera) {
        String teks;
        Color warna;

        if (kedaluwarsa.isEmpty() && segera.isEmpty()) {
            warna = BANNER_HIJAU;
            teks = "<html><b>Semua bahan masih aman.</b></html>";
        } else {
            StringBuilder sb = new StringBuilder("<html>");
            if (!kedaluwarsa.isEmpty()) {
                sb.append("<b>PERINGATAN: ").append(kedaluwarsa.size())
                  .append(" bahan sudah/hari ini kedaluwarsa</b> &rarr; ")
                  .append(ringkasNama(kedaluwarsa));
            }
            if (!segera.isEmpty()) {
                if (!kedaluwarsa.isEmpty()) sb.append("<br>");
                sb.append("<b>Segera: ").append(segera.size())
                  .append(" bahan kedaluwarsa dalam &le; ").append(BATAS_PERINGATAN)
                  .append(" hari</b> &rarr; ").append(ringkasNama(segera));
            }
            sb.append("</html>");
            teks = sb.toString();
            warna = !kedaluwarsa.isEmpty() ? BANNER_MERAH : BANNER_ORANYE;
        }

        panelPeringatan.setBackground(warna);
        lblPeringatan.setText(teks);

        // Tampil lagi hanya jika isi peringatan berbeda dari yang sudah ditutup
        panelPeringatan.setVisible(!teks.equals(pesanDitutup));
        getContentPane().revalidate();
        getContentPane().repaint();
    }
        
    private String ringkasNama(List<String> daftar) {
        int batas = Math.min(3, daftar.size());
        String hasil = String.join(", ", daftar.subList(0, batas));
        if (daftar.size() > batas) {
            hasil += " dan " + (daftar.size() - batas) + " lainnya";
        }
        return hasil;
    }

    // ===== Load data dari database ke tabel =====
    private void muatData() {
        tableModel.setRowCount(0);
        dataList = new ArrayList<>();
        try {
            dataList = controller.cari(jTextField3.getText());
            LocalDate hariIni = LocalDate.now();
            int nomor = 1;

            List<String> kedaluwarsa = new ArrayList<>();
            List<String> segera = new ArrayList<>();

            // Banner selalu berdasarkan SEMUA data, bukan hasil pencarian
            boolean sedangMencari = !jTextField3.getText().trim().isEmpty();
            for (BahanMakanan b : (sedangMencari ? controller.ambilSemua() : dataList)) {
                String status = hitungStatus(b.getTanggalKedaluwarsa(), hariIni);
                if (status.startsWith("SUDAH") || status.startsWith("HARI INI")) {
                    kedaluwarsa.add(b.getNama());
                } else if (status.startsWith("SEGERA")) {
                    segera.add(b.getNama());
                }
            }

            for (BahanMakanan b : dataList) {
                String status = hitungStatus(b.getTanggalKedaluwarsa(), hariIni);
                tableModel.addRow(new Object[]{
                    nomor++,
                    b.getNama(),
                    b.getTanggalKedaluwarsa().format(FORMAT),
                    status
                });
            }
            perbaruiBanner(kedaluwarsa, segera);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Gagal memuat database: " + e.getMessage(),
                    "Error Koneksi", JOptionPane.ERROR_MESSAGE);
        }
    }

    private LocalDate validasiTanggal(String tglStr) {
        try {
            return LocalDate.parse(tglStr, FORMAT);
        } catch (DateTimeParseException e) {
            JOptionPane.showMessageDialog(this,
                    "Format tanggal salah! Gunakan format: dd-MM-yyyy (contoh: 31-12-2026)",
                    "Format Salah", JOptionPane.ERROR_MESSAGE);
            return null;
        }
    }

    private void tambahData() {
        String nama = jTextField1.getText().trim();
        if (nama.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Nama bahan tidak boleh kosong!",
                    "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }
        LocalDate tanggal = validasiTanggal(jTextField2.getText().trim());
        if (tanggal == null) return;

        try {
            controller.tambah(nama, tanggal);
            JOptionPane.showMessageDialog(this, nama + " berhasil ditambahkan ke database!",
                    "Sukses", JOptionPane.INFORMATION_MESSAGE);
            muatData();
            kosongkanForm();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Gagal menyimpan data: " + e.getMessage(),
                    "Database Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void ubahData() {
        int row = jTable1.getSelectedRow();
        if (row == -1 || row >= dataList.size()) {
            JOptionPane.showMessageDialog(this, "Pilih baris data pada tabel yang ingin diubah!",
                    "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }
        int id = dataList.get(row).getId();
        String nama = jTextField1.getText().trim();
        if (nama.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Nama bahan tidak boleh kosong!",
                    "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }
        LocalDate tanggal = validasiTanggal(jTextField2.getText().trim());
        if (tanggal == null) return;

        try {
            controller.ubah(id, nama, tanggal);
            JOptionPane.showMessageDialog(this, "Data berhasil diubah di database!",
                    "Sukses", JOptionPane.INFORMATION_MESSAGE);
            muatData();
            kosongkanForm();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Gagal mengubah data: " + e.getMessage(),
                    "Database Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void hapusData() {
        int row = jTable1.getSelectedRow();
        if (row == -1 || row >= dataList.size()) {
            JOptionPane.showMessageDialog(this, "Pilih baris data pada tabel yang ingin dihapus!",
                    "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }
        BahanMakanan bahan = dataList.get(row);
        int id = bahan.getId();

        // Pilih alasan pembuangan -> dicatat ke Log Pembuangan (Wastage Log)
        String status = hitungStatus(bahan.getTanggalKedaluwarsa(), LocalDate.now());
        javax.swing.JComboBox<String> cmbAlasan = new javax.swing.JComboBox<>(BahanService.DAFTAR_ALASAN);
        if (!(status.startsWith("SUDAH") || status.startsWith("HARI INI"))) {
            cmbAlasan.setSelectedItem("Rusak / Busuk");
        }
        JPanel form = new JPanel(new BorderLayout(0, 6));
        form.add(new JLabel("<html>Hapus <b>" + bahan.getNama().replace("<", "&lt;")
                + "</b>?<br>Bahan akan dicatat ke Log Pembuangan.</html>"), BorderLayout.NORTH);
        form.add(new JLabel("Alasan dibuang:"), BorderLayout.CENTER);
        form.add(cmbAlasan, BorderLayout.SOUTH);

        int konfirmasi = JOptionPane.showConfirmDialog(this, form,
                "Konfirmasi Hapus", JOptionPane.OK_CANCEL_OPTION, JOptionPane.QUESTION_MESSAGE);

        if (konfirmasi == JOptionPane.OK_OPTION) {
            try {
                controller.hapus(id, String.valueOf(cmbAlasan.getSelectedItem()));
                JOptionPane.showMessageDialog(this, "Data berhasil dihapus dan dicatat ke Log Pembuangan!",
                        "Sukses", JOptionPane.INFORMATION_MESSAGE);
                muatData();
                kosongkanForm();
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Gagal menghapus data: " + e.getMessage(),
                        "Database Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }

    private void kosongkanForm() {
        jTextField1.setText("");
        jTextField2.setText("");
        jTable1.clearSelection();
    }
    
